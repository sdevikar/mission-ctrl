"""Tests for AGENTS.md sync: template, sanitization, post-skill hook (M3)."""

from __future__ import annotations

import time
from pathlib import Path

import pytest
from mission_ctrl_core.stores import IntentStore
from mission_ctrl_pi.agents_sync import (
    SanitizationError,
    render_agents_md,
    sanitize_field,
    write_agents_md,
)
from mission_ctrl_pi.schemas import AddIdeaInput, InitInput
from mission_ctrl_pi.skills import intent_add_idea, intent_init

CORE_FIXTURES = Path(__file__).resolve().parents[2] / "core" / "tests" / "fixtures"
SNAPSHOTS = Path(__file__).parent / "snapshots"


def _init_store(tmp_path) -> IntentStore:
    store = IntentStore(tmp_path)
    intent_init(
        InitInput(project_name="SyncApp", mission="Synced mission"), store=store
    )
    return store


