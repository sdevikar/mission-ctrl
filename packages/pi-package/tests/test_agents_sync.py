@pytest.mark.parametrize(
    "value",
    [
        "Nice title <!-- hidden -->",
        "Trailing comment -->",
        "Example ```python print('x')",
        "Multiline\n```js\nalert(1)",
    ],
)
def test_sanitize_field_rejects_injection_vectors(value):
    with pytest.raises(SanitizationError):
        sanitize_field(value)


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        ("# Heading hijack", "\\# Heading hijack"),
        ("## Sub head", "\\# Sub head"),
        ("[click](http://evil.example)", "\\[click\\](http://evil.example)"),
        ("Use `code` here", "Use \\`code\\` here"),
        ("plain title", "plain title"),
        ("", ""),
        (None, ""),
    ],
)
def test_sanitize_field_escapes_markdown(value, expected):
    assert sanitize_field(value) == expected


def _spec_with_title(store: IntentStore, title: str):
    """Drive add-idea → triage → spec-create so `title` lands in the render."""
    from mission_ctrl_pi.schemas import SpecCreateInput, TriageInput
    from mission_ctrl_pi.skills import intent_spec_create, intent_triage

    add = intent_add_idea(AddIdeaInput(title="Sync feature"), store=store)
    intent_triage(
        TriageInput(idea_id=add.idea_id, bucket="mvp", alignment_verdict="Core"),
        store=store,
    )
    return intent_spec_create(
        SpecCreateInput(idea_id=add.idea_id, title=title), store=store
    )


def test_skill_write_with_injection_title_raises(tmp_path):
    """Post-skill sync rejects injection-attempt titles via SanitizationError."""
    store = _init_store(tmp_path)
    with pytest.raises(SanitizationError):
        _spec_with_title(store, "Feature <!-- inject -->")
    # The spec write itself succeeded; only the post-write sync rejected it.
    assert len(store.specs.read().nodes) == 1


def test_rendered_output_escapes_hostile_titles(tmp_path):
    store = _init_store(tmp_path)
    _spec_with_title(store, "# Not a heading")
    rendered = render_agents_md(store)
    assert "\\# Not a heading" in rendered
    assert "\n# Not a heading" not in rendered


def test_init_with_hostile_mission_escapes(tmp_path):
    store = IntentStore(tmp_path)
    intent_init(
        InitInput(project_name="SyncApp", mission="# Hijack mission"), store=store
    )
    rendered = render_agents_md(store)
    assert "\\# Hijack mission" in rendered


