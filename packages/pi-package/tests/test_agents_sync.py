# Template + snapshot
# ---------------------------------------------------------------------------


def test_render_contains_expected_sections(tmp_path):
    rendered = render_agents_md(_init_store(tmp_path))
    assert "<!-- Auto-generated by Mission Ctrl. Do not edit manually. -->" in rendered
    assert "Synced mission" in rendered
    assert "## Current Focus" in rendered
    assert "## Backlog Summary" in rendered
    assert "intent:add-idea" in rendered


def test_snapshot_mid_flight():
    store = IntentStore(CORE_FIXTURES / "mid-flight")
    expected = (SNAPSHOTS / "agents_md_mid_flight.md").read_text(encoding="utf-8")
    assert render_agents_md(store) == expected


def test_render_is_deterministic(tmp_path):
    store = _init_store(tmp_path)
    assert render_agents_md(store) == render_agents_md(store)


