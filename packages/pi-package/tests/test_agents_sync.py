def test_init_writes_agents_md_next_to_intent(tmp_path):
    _init_store(tmp_path)
    agents_md = tmp_path / "AGENTS.md"
    assert agents_md.is_file()
    assert "Synced mission" in agents_md.read_text(encoding="utf-8")


def test_skill_write_updates_agents_md(tmp_path):
    store = _init_store(tmp_path)
    agents_md = tmp_path / "AGENTS.md"
    before = agents_md.read_text(encoding="utf-8")
    assert "Untriaged: 0" in before
    intent_add_idea(AddIdeaInput(title="Fresh idea"), store=store)
    after = agents_md.read_text(encoding="utf-8")
    assert "Untriaged: 1" in after
    assert before != after


def test_sync_completes_within_one_second(tmp_path):
    store = _init_store(tmp_path)
    intent_add_idea(AddIdeaInput(title="Timed idea"), store=store)
    start = time.perf_counter()
    write_agents_md(store)
    assert time.perf_counter() - start < 1.0
